"""
SCRUM-46: Attendee Registration and Update Notifications

User Story
----------
As an Attendee, I want to receive notifications about my registration status,
so that I can confirm my place and stay updated on event changes.

Acceptance Criteria
-------------------
AC1: Given an Attendee successfully registers for an event, the system sends an
     in-app notification confirming their registration with the event name,
     date, time, venue, and registration reference number.
AC2: Given an Attendee successfully withdraws their registration, the system
     sends an in-app notification confirming the withdrawal with the event
     name.
AC3: Given an event cancellation takes effect, or a change to its date, time or
     venue is approved and applied, all currently registered Attendees receive
     an in-app notification with the event name and cancellation status or
     updated details, as applicable.

Real
----
- AC1 (venue only): the save adapter looks up the event's approved venue and
  adds its name to the notification data sent to Registration Service.
- AC3 (list view only): GET /registrations keeps a cancelled event in the
  attendee's list with its status.

Doubled
-------
- GET /registrations: Stub (monkeypatch) - registrations, user, confirmed
  events and event summaries.
- Save adapter: respx - Venue Availability, Venue and Registration Service
  HTTP calls. The request sent to Registration Service is matched exactly.

Not proven
----------
- AC1: the event name, date and time in the notification data (built in the
  register route -> test_scrum37_event_registration.py) and the registration
  reference number (generated by Registration Service).
- AC1/AC2: that Registration Service stores the confirmation/withdrawal and
  the dispatcher delivers it (-> registration-service
  test_attendee_notifications.py and notification-service consumer tests).
- AC2: the withdrawal request and its event name (-> test_scrum39_withdraw_registration.py).
- AC3: the change and cancellation notices themselves (-> event-service
  SCRUM-46 notification tests; NOT COVERED here).
"""

